#!/usr/bin/env python3
"""Generate exact GPT-2 splitter character tables (offline, one-time).
Uses Python unicodedata + re semantics as the oracle; emits C range tables.
L = unicodedata category L* (matches regex \\p{L} on str patterns).
N = category N* (matches \\p{N}).
S = codepoints matching re \\s (includes NEL, NBSP, hair space, etc.).
"""
import re
import unicodedata

ws_pat = re.compile(r"\s")


def ranges(pred):
    out = []
    start = None
    for cp in range(0x110000):
        try:
            ch = chr(cp)
        except ValueError:
            continue
        if unicodedata.category(ch) in ("Cs",):
            is_in = False
        else:
            is_in = pred(ch)
        if is_in and start is None:
            start = cp
        elif not is_in and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


L = ranges(lambda ch: unicodedata.category(ch).startswith("L"))
N = ranges(lambda ch: unicodedata.category(ch).startswith("N"))
S = ranges(lambda ch: bool(ws_pat.match(ch)))


def emit(name, rs):
    print(f"static const uint32_t {name}[] = {{")
    for a, b in rs:
        print(f"    0x{a:X}, 0x{b:X},")
    print("};")
    print(f"static const int {name}_N = {len(rs)};")


print("/* generated by tools/gen_unitables.py — do not hand-edit */")
print("#include <stdint.h>")
print()
emit("UNI_L", L)
print()
emit("UNI_N", N)
print()
emit("UNI_S", S)
print()
print("static int uni_in(const uint32_t *t, int n, uint32_t cp) {")
print("    int lo = 0, hi = n - 1;")
print("    while (lo <= hi) {")
print("        int m = (lo + hi) / 2;")
print("        if (cp < t[2 * m]) hi = m - 1;")
print("        else if (cp > t[2 * m + 1]) lo = m + 1;")
print("        else return 1;")
print("    }")
print("    return 0;")
print("}")
print()
print("int uni_is_letter(int cp) { return cp >= 0 && uni_in(UNI_L, UNI_L_N, (uint32_t)cp); }")
print("int uni_is_number(int cp) { return cp >= 0 && uni_in(UNI_N, UNI_N_N, (uint32_t)cp); }")
print("int uni_is_space(int cp) { return cp >= 0 && uni_in(UNI_S, UNI_S_N, (uint32_t)cp); }")
